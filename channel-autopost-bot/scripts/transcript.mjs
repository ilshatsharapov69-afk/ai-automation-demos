// Writes test/transcript.md: the three screenshot conversations as plain text (real bot output).
//   npm run transcript
import { writeFileSync } from 'node:fs';
import { runScenarios } from './scenarios.mjs';

const hhmm = (ms) => new Date(ms).toISOString().slice(11, 16);
const quote = (s) => s.split('\n').map((l) => `> ${l}`).join('\n');
let md = '# Bot transcript\n\nGenerated by `npm run transcript` from the real Worker code (offline: Telegram calls captured, AI drafts from the offline template). Times are UTC.\n';
for (const s of await runScenarios()) {
  md += `\n## ${s.title}\n\n`;
  for (const i of s.chat.items) {
    if (i.kind === 'user') md += `**${hhmm(i.at)} user:** ${i.photo ? '[photo] ' : ''}${i.text.replace(/\n/g, ' ')}\n\n`;
    if (i.kind === 'press') md += `*${hhmm(i.at)} presses* \`${i.text}\`\n\n`;
    if (i.kind === 'toast') md += `*(toast: ${i.text})*\n\n`;
    if (i.kind === 'service') md += `---\n*${i.text}*\n\n`;
    if (i.kind === 'bot') {
      md += `**${hhmm(i.at)} bot:**${i.photo ? ' [photo]' : ''}${i.edited ? ' *(edited after the button press)*' : ''}\n\n${quote(i.text)}\n\n`;
      const rows = i.buttons.map((r) => r.map((b) => `[${b.text}]`).join(' ')).filter(Boolean);
      if (rows.length) md += rows.map((r) => `> ${r}`).join('\n') + '\n\n';
    }
  }
}
writeFileSync(new URL('../test/transcript.md', import.meta.url), md);
console.log('wrote test/transcript.md');
